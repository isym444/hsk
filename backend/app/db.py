_NAMED_PARAM = re.compile(r":([A-Za-z_][A-Za-z0-9_]*)")


def _to_pyformat(sql: str) -> str:
    """Rewrites ``?``/``:name`` placeholders into psycopg's ``%`` form.

    The SQL in this codebase contains no literal ``%`` and no ``::`` casts, so
    the rewrite is unambiguous. (Adding either would need this function to
    escape them first.)
    """
    sql = sql.replace("?", "%s")
    return _NAMED_PARAM.sub(lambda match: f"%({match.group(1)})s", sql)


def _statements(script: str) -> Iterator[str]:
    """Splits a multi-statement script into individual statements.

    Line comments and blank fragments are dropped first: a ``;`` inside a
    ``--`` comment is easy to write and would otherwise cut a statement in
    half. (No statement here contains a ``;`` inside a string literal.)
    """
    without_comments = "\n".join(line.split("--", 1)[0] for line in script.splitlines())
    for statement in without_comments.split(";"):
        stripped = statement.strip()
        if stripped:
            yield stripped


def _catalogue_rows(questions: Iterable[dict]) -> list[dict]:
    """Normalises catalogue rows to the column types before insertion.

    ``scoreable`` arrives from the JSON catalogue as a Python ``bool``. SQLite
    happily stores that in an ``INTEGER`` column, but PostgreSQL types the bound
    parameter as ``boolean`` and then refuses the insert with a
    ``DatatypeMismatch``. Coercing once here keeps one INSERT for both backends
    and keeps the column honest (0/1, as the schema declares).
    """
    return [{**row, "scoreable": int(bool(row.get("scoreable")))} for row in questions]


class PgConnection:
    """A DB-API facade over a psycopg connection, matching ``sqlite3``."""

    def __init__(self, conn: Any, pool: Any | None = None) -> None:
        self.raw = conn
        self._pool = pool
        self._closed = False

    # -- queries ---------------------------------------------------------- #
    def execute(self, sql: str, params: Any = None) -> Any:
        cursor = self.raw.cursor()
        cursor.execute(_to_pyformat(sql), params)
        return cursor

    def executemany(self, sql: str, params: Iterable[Any]) -> Any:
        cursor = self.raw.cursor()
        cursor.executemany(_to_pyformat(sql), params)
        return cursor

    def executescript(self, script: str) -> None:
        with self.raw.cursor() as cursor:
            for statement in _statements(script):
                cursor.execute(statement)

    # -- transactions ----------------------------------------------------- #
    def commit(self) -> None:
        self.raw.commit()

    def rollback(self) -> None:
        self.raw.rollback()

    def __enter__(self) -> "PgConnection":
        return self

    def __exit__(self, exc_type: Any, exc: Any, tb: Any) -> None:
        # Mirrors sqlite3: commit or roll back, but leave the connection usable
        # (callers keep querying after the block).
        if exc_type is None:
            self.raw.commit()
        else:
            self.raw.rollback()

    def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        # A pooled connection always goes back idle, never mid-transaction.
        self.raw.rollback()
        if self._pool is not None:
            self._pool.putconn(self.raw)
        else:  # pragma: no cover - only used with a bare connection
            self.raw.close()


_SCHEMA_NAME = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")


def validate_schema_name(name: str) -> str:
    """Rejects anything that is not a plain lowercase identifier.

    The schema name is interpolated into DDL (there is no bind parameter for an
    identifier), so this is the boundary that keeps it from being a hole.
    """
    if not _SCHEMA_NAME.match(name):
        raise ValueError(
            f"HSK_DB_SCHEMA must look like a lowercase SQL identifier, got {name!r}"
        )
    return name


class PostgresDatabase:
    """Owns a psycopg connection pool and hands out pooled connections."""

    dialect = "postgresql"

    def __init__(
        self,
        dsn: str,
        min_size: int = 1,
        max_size: int = 5,
        timeout: float = 10.0,
        schema: str | None = None,
    ) -> None:
        if ConnectionPool is None:  # pragma: no cover
            raise RuntimeError(
                "HSK_DATABASE_URL is set but psycopg is not installed. "
                "Install it with: pip install 'psycopg[binary,pool]'"
            )
        self.dsn = dsn
        self.min_size = min_size
        self.max_size = max_size
        self.timeout = timeout
        #: When set, the review tables live in this schema instead of the
        #: connection's default. Used when the database is shared with another
        #: application, so the two cannot collide on names like `sessions`.
        self.schema = validate_schema_name(schema) if schema else None
        self._pool = ConnectionPool(
            conninfo=dsn,
            min_size=min_size,
            max_size=max_size,
            open=False,
            # dict_row makes a row behave like sqlite3.Row for the statistics
            # code, which reads columns by name.
            kwargs={
                "row_factory": dict_row,
                # Supabase's pooler (and most transaction poolers) cannot host
                # server-side prepared statements; keep everything unprepared.
                "prepare_threshold": None,
            },
            # Set per connection rather than in the DSN: a `SET` travels through
            # the pooler as ordinary SQL, and this also pins `current_schema()`,
            # which the in-place column migration relies on.
            configure=self._use_schema if self.schema else None,
        )

    def _use_schema(self, conn: Any) -> None:
        conn.execute(f'SET search_path TO "{self.schema}", public')
        conn.commit()

    # -- lifecycle -------------------------------------------------------- #
    def open(self) -> None:
        self._pool.open(wait=True, timeout=self.timeout)

    def close(self) -> None:
        self._pool.close()

    def connect(self) -> PgConnection:
        return PgConnection(self._pool.getconn(timeout=self.timeout), self._pool)

    # -- schema ----------------------------------------------------------- #
    def init_schema(self) -> None:
        with self.connect() as conn:
            if self.schema:
                # Checked before creating, rather than `CREATE SCHEMA IF NOT
                # EXISTS`: the latter still demands CREATE on the *database*
                # even when the schema is already there, which a least-privilege
                # role deliberately does not have. The pool has already pointed
                # search_path here (`SET` allows a schema that does not exist
                # yet), so everything below lands in the right place.
                found = conn.execute(
                    "SELECT 1 FROM pg_namespace WHERE nspname = ?", (self.schema,)
                ).fetchone()
                if not found:
                    logger.info("creating schema %s", self.schema)
                    conn.execute(f'CREATE SCHEMA "{self.schema}"')
            conn.executescript(TABLES_POSTGRES)
            self._add_missing_columns(conn)
            conn.executescript(INDEXES_POSTGRES)
            conn.commit()

    @staticmethod
    def _add_missing_columns(conn: PgConnection) -> None:
        """Upgrades a database created before later columns existed.

        ``CREATE TABLE IF NOT EXISTS`` leaves an existing table alone, so any
        column added to the schema after the first release has to be applied by
        hand. The defaults make each one work on a table that already has rows:
        pre-account rows keep ``''`` (nobody's), and pre-level rows keep the
        level they were created for.
        """
        additions = (
            ("sessions", "user_id", "TEXT NOT NULL DEFAULT ''"),
            ("reviews", "user_id", "TEXT NOT NULL DEFAULT ''"),
            ("questions", "level", "TEXT NOT NULL DEFAULT 'HSK4'"),
        )
        for table, column, ddl in additions:
            found = conn.execute(
                "SELECT COUNT(*) AS n FROM information_schema.columns"
                " WHERE table_schema = current_schema()"
                " AND table_name = ? AND column_name = ?",
                (table, column),
            ).fetchone()["n"]
            if not found:
                logger.info("adding %s.%s to an existing database", table, column)
                conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")

    def describe(self) -> str:
        """A log-safe identifier: never includes the password."""
        try:
            parts = conninfo_to_dict(self.dsn)
        except Exception:  # pragma: no cover - malformed DSN
            return "postgresql"
        host = parts.get("host", "?")
        port = parts.get("port", "5432")
        name = parts.get("dbname", "?")
        return f"postgresql://{host}:{port}/{name}"

    # -- seeding ---------------------------------------------------------- #
    def seed_catalogue(self, questions: Iterable[dict], keep_stale: bool = True) -> int:
        rows = _catalogue_rows(questions)
        with self.connect() as conn:
            conn.executemany(
                """
                INSERT INTO questions
                    (question_key, paper, level, category, kind, number, part, scoreable, label, active)
                VALUES (:key, :paper, :level, :category, :kind, :number, :part, :scoreable, :label, 1)
                ON CONFLICT(question_key) DO UPDATE SET
                    paper     = excluded.paper,
                    level     = excluded.level,
                    category  = excluded.category,
                    kind      = excluded.kind,
                    number    = excluded.number,
                    part      = excluded.part,
                    scoreable = excluded.scoreable,
                    label     = excluded.label,
                    active    = 1
                """,
                rows,
            )
            if rows:
                keys = [row["key"] for row in rows]
                if keep_stale:
                    conn.execute(
                        "UPDATE questions SET active = 0 WHERE question_key <> ALL(%s)",
                        (keys,),
                    )
                else:
                    conn.execute(
                        "DELETE FROM questions WHERE question_key <> ALL(%s)",
                        (keys,),
                    )
            conn.commit()
        return len(rows)


