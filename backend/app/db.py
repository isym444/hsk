class Database:
    """Owns the SQLite database path and hands out short-lived connections."""

    dialect = "sqlite"

    def __init__(self, path: str | Path) -> None:
        self.path = Path(path)

    def connect(self) -> sqlite3.Connection:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(
            self.path,
            # FastAPI runs sync endpoints in a threadpool; a connection is
            # created and closed inside a single request, but not necessarily
            # on the same thread, so the default same-thread guard is too strict.
            check_same_thread=False,
            timeout=10.0,
        )
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        conn.execute("PRAGMA journal_mode = WAL")
        conn.execute("PRAGMA busy_timeout = 5000")
        return conn

    def open(self) -> None:  # symmetry with PostgresDatabase
        pass

    def close(self) -> None:  # symmetry with PostgresDatabase
        pass

    def describe(self) -> str:
        return str(self.path)

    def init_schema(self) -> None:
        with self.connect() as conn:
            conn.executescript(TABLES_SQLITE)
            self._add_missing_columns(conn)
            conn.executescript(INDEXES_SQLITE)
            conn.commit()

    @staticmethod
    def _add_missing_columns(conn: sqlite3.Connection) -> None:
        """Upgrades a database created before later columns existed.

        See :meth:`PostgresDatabase._add_missing_columns`; SQLite has no
        ``information_schema``, so each table is inspected directly.
        """
        additions = (
            ("sessions", "user_id", "TEXT NOT NULL DEFAULT ''"),
            ("reviews", "user_id", "TEXT NOT NULL DEFAULT ''"),
            ("questions", "level", "TEXT NOT NULL DEFAULT 'HSK4'"),
        )
        for table, column, ddl in additions:
            columns = {row["name"] for row in conn.execute(f"PRAGMA table_info({table})")}
            if column not in columns:
                logger.info("adding %s.%s to an existing database", table, column)
                conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")

    def seed_catalogue(self, questions: Iterable[dict], keep_stale: bool = True) -> int:
        """Upserts the question catalogue.

        Questions that disappeared from the catalogue are deactivated rather
        than deleted (`keep_stale=True`) so review history keeps its foreign
        key target. Pass ``keep_stale=False`` only when the history is
        disposable.
        """
        rows = _catalogue_rows(questions)
        with self.connect() as conn:
            conn.executemany(
                """
                INSERT INTO questions
                    (question_key, paper, level, category, kind, number, part, scoreable, label, active)
                VALUES (:key, :paper, :level, :category, :kind, :number, :part, :scoreable, :label, 1)
                ON CONFLICT(question_key) DO UPDATE SET
                    paper     = excluded.paper,
                    level     = excluded.level,
                    category  = excluded.category,
                    kind      = excluded.kind,
                    number    = excluded.number,
                    part      = excluded.part,
                    scoreable = excluded.scoreable,
                    label     = excluded.label,
                    active    = 1
                """,
                rows,
            )
            if rows:
                placeholders = ",".join("?" for _ in rows)
                keys = [row["key"] for row in rows]
                if keep_stale:
                    conn.execute(
                        f"UPDATE questions SET active = 0 WHERE question_key NOT IN ({placeholders})",
                        keys,
                    )
                else:
                    conn.execute(
                        f"DELETE FROM questions WHERE question_key NOT IN ({placeholders})",
                        keys,
                    )
            conn.commit()
        return len(rows)


def create_database(
    connection_url: str | None = None,
    path: str | Path | None = None,
    min_size: int = 1,
    max_size: int = 5,
    schema: str | None = None,
) -> Database | PostgresDatabase:
    """Builds the backend the environment asks for.

    A ``connection_url`` (``postgresql://...``) wins; otherwise a SQLite file at
    ``path``. An explicit ``path`` always forces SQLite, so tests and ad-hoc runs
    can point at a throwaway database even when ``HSK_DATABASE_URL`` is exported.

    ``schema`` is PostgreSQL-only and ignored by SQLite, which has no schemas.
    """
    if connection_url:
        return PostgresDatabase(
            connection_url, min_size=min_size, max_size=max_size, schema=schema
        )
    if path is None:
        path = os.environ.get("HSK_DB_PATH") or (
            Path(__file__).resolve().parent.parent / "data" / "hsk_reviews.sqlite3"
        )
    return Database(path)


